import random
import statistics
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.data import generate_transactions  # noqa: E402
from app.scorer import get_scorer  # noqa: E402
from app.store import STATUSES, TRANSITIONS, Store, StoreError  # noqa: E402


def queue_quality(store, df) -> dict:
    """Ground truth stays outside the database; compare the queue with it afterwards."""
    truth = df.set_index("txn_id")["is_fraud"]
    ranked = []
    off = 0
    while off < 1000:
        ranked += store.list(limit=200, offset=off)["items"]
        off += 200
    y = np.array([truth[r["txn_id"]] for r in ranked])
    base = float(truth.mean())
    res = {"transactions": int(len(df)), "fraud_rate": base, "precision_at_50": float(y[:50].mean()),
           "precision_at_200": float(y[:200].mean()), "precision_at_1000": float(y.mean()),
           "random_ranking_precision": base}
    tot_hi = store.list(band="high", limit=1)["total"]
    all_hi = []
    off = 0
    while off < tot_hi:
        all_hi += [r["txn_id"] for r in store.list(band="high", limit=200, offset=off)["items"]]
        off += 200
    hy = truth[all_hi].to_numpy()
    res["high_band"] = {"alerts": int(tot_hi), "alerts_per_day": tot_hi / 90.0, "precision": float(hy.mean()) if len(hy) else None,
                        "recall": float(hy.sum() / truth.sum())}
    return res


def workflow_fuzz(df, ops: int = 3000) -> dict:
    sc = get_scorer()
    st = Store(os.path.join(tempfile.mkdtemp(), "fz.db"), sc)
    st.ingest(df.iloc[:400])
    ids = [r["txn_id"] for r in st.list(limit=200)["items"]]
    rng = random.Random(0)
    model = {i: "new" for i in ids}
    ok = rejected = mismatches = 0
    for _ in range(ops):
        t, new = rng.choice(ids), rng.choice(STATUSES)
        allowed = new in TRANSITIONS[model[t]]
        try:
            st.set_status(t, new, rng.choice(["alice", "bob", "carol"]), "fuzz note")
            ok += 1
            mismatches += 0 if allowed else 1
            model[t] = new
        except StoreError:
            rejected += 1
            mismatches += 1 if allowed else 0
    final_ok = all(st.get(i)["status"] == model[i] for i in ids)
    audit = st.stats()["audit_rows"]
    return {"operations": ops, "accepted": ok, "rejected": rejected, "decision_mismatches_vs_model": mismatches,
            "final_states_match_model": final_ok, "audit_rows": audit, "audit_rows_expected": 1 + ok,
            "audit_count_exact": audit == 1 + ok}


def latency(df) -> dict:
    sc = get_scorer()
    st = Store(os.path.join(tempfile.mkdtemp(), "lat.db"), sc)
    t0 = time.perf_counter()
    st.ingest(df)
    ingest_s = time.perf_counter() - t0
    qs = []
    for i in range(100):
        t0 = time.perf_counter()
        st.list(band="high" if i % 2 else None, channel="online" if i % 3 == 0 else None, min_score=0.5, limit=50, offset=(i % 5) * 50)
        qs.append((time.perf_counter() - t0) * 1e3)
    t0 = time.perf_counter()
    st.stats()
    stats_ms = (time.perf_counter() - t0) * 1e3
    return {"rows": int(len(df)), "ingest_seconds": ingest_s, "list_query_ms": {"median": statistics.median(qs), "p95": sorted(qs)[94]}, "stats_ms": stats_ms}


def to_md(r):
    q, f, l, e = r["queue_quality"], r["workflow_fuzz"], r["latency"], r["environment"]
    h = q["high_band"]
    return "\n".join([
        "# Results (generated by `scripts/evaluate.py`)", "",
        f"- Created (UTC): {r['created_utc']}; machine: {e['platform']}; Python {e['python']}; CPUs {e['cpu_count']}", "",
        f"## Queue quality on held-out synthetic data ({q['transactions']} transactions, fraud rate {q['fraud_rate']:.2%}, scorer trained on a different seed)", "",
        "| Measure | Value |", "|---|---:|",
        f"| Precision in top 50 / 200 / 1000 of the ranked queue | {q['precision_at_50']:.2f} / {q['precision_at_200']:.2f} / {q['precision_at_1000']:.2f} |",
        f"| Precision of a random queue | {q['random_ranking_precision']:.3f} |",
        f"| High-band alerts (total, per day) | {h['alerts']} ({h['alerts_per_day']:.1f}/day) |",
        f"| High-band precision / recall | {h['precision']:.2f} / {h['recall']:.2f} |", "",
        "## Workflow integrity (randomised operations against an independent model)", "",
        f"{f['operations']} random status changes by 3 reviewers: {f['accepted']} accepted, {f['rejected']} rejected, "
        f"{f['decision_mismatches_vs_model']} disagreements with the model; final states match: {f['final_states_match_model']}; "
        f"audit rows {f['audit_rows']} (expected {f['audit_rows_expected']}): exact = {f['audit_count_exact']}.", "",
        "## Latency (SQLite file, single process)", "",
        f"Ingest + score {l['rows']} rows: {l['ingest_seconds']:.2f} s; filtered ranked list query: median {l['list_query_ms']['median']:.1f} ms, "
        f"p95 {l['list_query_ms']['p95']:.1f} ms; stats: {l['stats_ms']:.1f} ms.", "",
        "Caveats: synthetic data; recall is limited because 20% of synthetic fraud is indistinguishable from legitimate behaviour; latency is from a 1-core sandbox, not a production database.", ""])


def main():
    df = generate_transactions(20000, 90, 123)
    st = Store(os.path.join(tempfile.mkdtemp(), "q.db"), get_scorer())
    st.ingest(df)
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "cpu_count": os.cpu_count()},
         "queue_quality": queue_quality(st, df), "workflow_fuzz": workflow_fuzz(df), "latency": latency(df)}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
